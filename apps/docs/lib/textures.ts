/**
 * Lift a grey off pure black and pure white.
 *
 * The creeper's mouth is #000000 in the texture, and pure black is the one value this site does not use:
 * it is harsher than anything else on the page and reads as a hole rather than as a colour. Everything
 * is mapped proportionally into 0x2E-0xF2, so a texture keeps every step of its contrast, just inside the
 * range the rest of the palette lives in.
 */
export function soften(level: number) {
  return Math.round(0x2e + (level * (0xf2 - 0x2e)) / 255);
}
