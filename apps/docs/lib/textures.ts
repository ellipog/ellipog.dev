/**
 * Minecraft textures, as grayscale.
 *
 * Sampled from the vanilla 1.21.1 client jar (`assets/minecraft/textures/`) and reduced to grey, so the
 * figures on this site are the real blocks and mobs rather than drawings of them:
 *
 *   - **grass top**: `block/grass_block_top.png`, which ships grey, multiplied by the plains grass tint
 *     `#91BD59` -- the colour the game paints it -- before it is reduced.
 *   - **grass side**: `block/grass_block_side.png` with `grass_block_side_overlay.png` tinted the same way
 *     and laid over it, as the game composites the two.
 *   - **bottom**: `block/dirt.png`.
 *   - **creeper**: `entity/creeper/creeper.png`, the head front -- pixels (8,8) to (15,15).
 *   - **stone, oak log, oak leaves**: `block/stone.png`, `oak_log.png`, `oak_log_top.png` and
 *     `oak_leaves.png`, for the hero's island. The leaves are tinted plains foliage `#77AB2F` first.
 *   - **everything after the leaves**: the blocks the hero's other structures are built from -- sand and
 *     sandstone, cobblestone, planks, glass, obsidian, netherrack, stone bricks, gold, deepslate and three
 *     ores -- each its `block/<name>.png`, plain luminance. Glass keeps its holes: anything under half
 *     alpha is 0, as the leaves' are. Opaque pixels are floored at 1, so a black texel is never a hole.
 *
 * **The creeper is plain luminance (Rec. 709), exactly.** It is all greens and black, and luminance keeps
 * every step of its mottling.
 *
 * **The grass block is not, and it cannot be.** In the game the grass reads against the dirt by hue, and
 * by luminance the two are nearly the same grey -- a median of 101 against 91 -- so a faithful conversion
 * is a block with no grass on it. The block is reduced through a green filter instead, the way a
 * photographer shoots black and white: luminance plus 1.2 x (G - R), which lifts the grass and sinks the
 * dirt and leaves the texture otherwise as it is.
 *
 * Each texture is a hex string, two digits per pixel, row by row. The pixels are Mojang's; the
 * conversion is ours. To regenerate, decode those files from any client jar and apply the same steps.
 */

const decode = (hex: string) => Uint8Array.from(hex.match(/../g) ?? [], (h) => parseInt(h, 16));

